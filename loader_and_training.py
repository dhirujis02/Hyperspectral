from torch.utils.data import Dataset, DataLoader

# 1. Define a custom PyTorch Dataset class named HSIDataset
class HSIDataset(Dataset):
    def __init__(self, data, labels):
        # 2. In the __init__ method of HSIDataset, accept data and labels as arguments and store them as attributes.
        self.data = data
        self.labels = labels

    def __len__(self):
        # 3. Implement the __len__ method to return the total number of samples in the dataset.
        return len(self.labels)

    def __getitem__(self, idx):
        # 4. Implement the __getitem__ method to return the data and label for a given index.
        return self.data[idx], self.labels[idx]

# 5. Create instances of HSIDataset for the training set and the testing set.
train_dataset = HSIDataset(X_train, y_train)
